// Writes the key constants for a .resx string table, so every lookup names a key the compiler checks.
// Usage: dotnet run tools/StringKeys.cs -- <table.resx> <Keys.cs> <namespace> <class>
// Each key becomes a const string named after it with dots replaced by underscores; a plural group
// (key.one, key.few, key.many, key.other, ...) becomes one constant for its base key. The drift test in
// each consuming test project fails when the constants and the table disagree, so run this after editing
// the English table.
using System.Globalization;
using System.Text;
using System.Xml.Linq;

if (args.Length != 4)
{
    Console.Error.WriteLine("Usage: dotnet run tools/StringKeys.cs -- <table.resx> <Keys.cs> <namespace> <class>");
    return 2;
}

var (resx, output, ns, cls) = (args[0], args[1], args[2], args[3]);
var suffixes = new[] { ".zero", ".one", ".two", ".few", ".many", ".other" };
var keys = XDocument.Load(resx).Root!
    .Elements("data")
    .Select(data => data.Attribute("name")!.Value)
    .Select(key => suffixes.FirstOrDefault(suffix => key.EndsWith(suffix, StringComparison.Ordinal)) is { } suffix ? key[..^suffix.Length] : key)
    .Distinct(StringComparer.Ordinal)
    .OrderBy(key => key, StringComparer.Ordinal)
    .ToList();

var builder = new StringBuilder();
builder.Append("// <auto-generated>\n");
builder.Append(CultureInfo.InvariantCulture, $"// The keys of {Path.GetFileName(resx)}. Regenerate with: dotnet run tools/StringKeys.cs -- {Path.GetRelativePath(".", resx).Replace('\\', '/')} {Path.GetRelativePath(".", output).Replace('\\', '/')} {ns} {cls}\n");
builder.Append("// </auto-generated>\n");
builder.Append(CultureInfo.InvariantCulture, $"namespace {ns};\n\n");
builder.Append(CultureInfo.InvariantCulture, $"/// <summary>The keys of <c>{Path.GetFileName(resx)}</c>, one constant per text; a plural group is one constant for its base key.</summary>\n");
builder.Append(CultureInfo.InvariantCulture, $"public static class {cls}\n{{\n");
foreach (var key in keys)
{
    builder.Append(CultureInfo.InvariantCulture, $"    /// <summary><c>{key}</c>.</summary>\n");
    builder.Append(CultureInfo.InvariantCulture, $"    public const string {key.Replace('.', '_')} = \"{key}\";\n\n");
}

if (keys.Count > 0)
{
    builder.Length -= 1;
}

builder.Append("}\n");
File.WriteAllText(output, builder.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"{keys.Count} keys written to {output}"));
return 0;
